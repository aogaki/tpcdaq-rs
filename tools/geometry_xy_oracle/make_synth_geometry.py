#!/usr/bin/env python3
"""Generate the SYNTHETIC strip geometry tests/fixtures/geometry_xy_synth.dat (TODO/125 lane A-5).

Every number written here is invented: DIAMOND SIZE / REFERENCE POINT are fictional and the
strip rows come from the disk-chord rule below. Nothing is copied from a real detector .dat
(CLAUDE.md: real geometry never enters the repository).

    python3 tools/geometry_xy_oracle/make_synth_geometry.py > tests/fixtures/geometry_xy_synth.dat

Layout (TPCReco GeometryTPC conventions, angles as in ELITPC: 0 / -120 / -60):

* Each plane has strips with OFF_STRIP = -N..N (strip number = OFF_STRIP + N + 1). The strip line
  is cut by a disk of radius R around the reference point; OFF_PAD (half-pad steps) and LEN_PADS
  (whole pads) cover that chord.
* V and W strips with |OFF_STRIP| <= N/2 are split into section 1 and section 2 (the others are
  section 0) -- "strips with two sections".
* U strip 2 has LEN_PADS = <integer> + 0.7  -> TPCReco truncates the pad count.
* W strip 2N+2 has LEN_PADS = 0.6           -> TPCReco drops the row (no segment).
* U strip 4 appears twice (different channel, different OFF_PAD / LEN_PADS) -> the later row wins.
* W strips 2N+3 .. 2N+6 are tolerance probes. The lines U(OFF_STRIP 0), V(OFF_STRIP 1) and
  W(OFF_STRIP -1) meet in one point P (hexagonal lattice: the three offsets sum to 0). Each probe
  lies on that W line and ends next to P: P sits at len = -0.5*pad_pitch - 0.5e-5 / - 2e-5 (start
  side) or len = length + 0.5e-5 / + 2e-5 (far side) along the probe. TPCReco accepts a crossing
  inside [-0.5*pad_pitch - tol, length + tol], tol = 1e-5 mm, so the first probe of each pair
  matches and the second does not. They pinned that tolerance in the oracle's MatchCrossPoint
  cases, which TODO/125 revision 2 removed together with the U/V/W coincidence projection; the
  rows stay so that this .dat and segments.json do not change.
"""

import math

DIAMOND = 1.25  # fictional
REF = (-20.5, 11.25)  # fictional
ANGLES = (0.0, -120.0, -60.0)
N = 6
R = 12.0
PROBE_LEN = 3

PAD_PITCH = DIAMOND * math.sqrt(3.0)
STRIP_PITCH = DIAMOND * 1.5


def unit(deg):
    rad = deg * (math.pi / 180.0)
    return (math.cos(rad), math.sin(rad))


def normalized(x, y):
    norm = math.sqrt(x * x + y * y)
    return (x / norm, y / norm)


UU, UV, UW = (unit(a) for a in ANGLES)
# TPCReco GeometryTPC::Load: pitch_U = -(W+V).Unit(), pitch_V = (U+W).Unit(), pitch_W = (V-U).Unit().
PU = tuple(-c for c in normalized(UW[0] + UV[0], UW[1] + UV[1]))
PV = normalized(UU[0] + UW[0], UU[1] + UW[1])
PW = normalized(UV[0] - UU[0], UV[1] - UU[1])


def chord(c):
    """(off_pad, len_pads) covering the disk chord at pitch coordinate c [mm]."""
    half = math.sqrt(R * R - c * c)
    # pad-0 centre at off_pad*pad_pitch; the segment starts half a pad earlier.
    off_pad = math.ceil((-half / PAD_PITCH + 0.5) * 2.0) / 2.0
    start = off_pad * PAD_PITCH - 0.5 * PAD_PITCH
    len_pads = max(1, int((half - start) / PAD_PITCH))
    return off_pad, len_pads


rows = []  # (dir, section, strip, off_pad, off_strip, len_pads) -- written as given


def add(plane, section, strip, off_pad, off_strip, len_pads):
    rows.append((plane, section, strip, off_pad, off_strip, len_pads))


for plane in ("U", "V", "W"):
    for off_strip in range(-N, N + 1):
        strip = off_strip + N + 1
        off_pad, len_pads = chord(off_strip * STRIP_PITCH)
        if plane != "U" and abs(off_strip) <= N // 2 and len_pads >= 4:
            first = len_pads // 2
            add(plane, 1, strip, off_pad, off_strip, first)
            add(plane, 2, strip, off_pad + first, off_strip, len_pads - first)
        elif plane == "U" and strip == 2:
            add(plane, 0, strip, off_pad, off_strip, f"{len_pads}.7")
        else:
            add(plane, 0, strip, off_pad, off_strip, len_pads)
        if plane == "U" and strip == 4:
            # duplicate (plane, section, strip): the later row wins in TPCReco mapByStrip.
            add(plane, 0, strip, off_pad + 1.0, off_strip, max(1, len_pads - 2))

# a row with LEN_PADS < 1.0: TPCReco drops it.
add("W", 0, 2 * N + 2, 0.0, N + 1, "0.6")

# P = U(OFF_STRIP 0) x V(OFF_STRIP 1), relative to the reference point.
# U line: s*UU (pitch offset 0). V line: STRIP_PITCH*PV + t*UV. Solve s*UU - t*UV = STRIP_PITCH*PV.
cx, cy = STRIP_PITCH * PV[0], STRIP_PITCH * PV[1]
det = UU[0] * (-UV[1]) - UU[1] * (-UV[0])
s = (cx * (-UV[1]) - cy * (-UV[0])) / det
P = (s * UU[0], s * UU[1])
along_w = P[0] * UW[0] + P[1] * UW[1]  # P = -STRIP_PITCH*PW + along_w*UW
probe_strip = 2 * N + 3
for len_at_p in (
    -0.5 * PAD_PITCH - 0.5e-5,
    -0.5 * PAD_PITCH - 2e-5,
    PROBE_LEN * PAD_PITCH + 0.5e-5,
    PROBE_LEN * PAD_PITCH + 2e-5,
):
    add("W", 0, probe_strip, repr((along_w - len_at_p) / PAD_PITCH), -1, PROBE_LEN)
    probe_strip += 1

print("# SYNTHETIC strip geometry for TODO/125 (strip_xy + TPCReco oracle).")
print("# Generated by tools/geometry_xy_oracle/make_synth_geometry.py -- every value is FICTIONAL,")
print("# nothing is copied from a real detector .dat (CLAUDE.md). Layout (see the script):")
print("# disk chords, V/W two-section strips, U2 fractional LEN_PADS, W%d LEN_PADS<1," % (2 * N + 2))
print("# U4 duplicated (later row wins), W%d..W%d tolerance probes." % (2 * N + 3, probe_strip - 1))
print("#")
print("ANGLES: %.1f %.1f %.1f" % ANGLES)
print("DIAMOND SIZE: %s" % DIAMOND)
print("REFERENCE POINT: %s %s" % REF)
print("DRIFT VELOCITY: 0.5")
print("SAMPLING RATE: 25.0")
print("TRIGGER DELAY: 5.0")
print("DRIFT CAGE ACCEPTANCE: -50.0 50.0")
print("#")
print("# DIR SECTION STRIP COBO ASAD AGET AGET_CH OFF_PAD OFF_STRIP LEN_PADS")
for index, (plane, section, strip, off_pad, off_strip, len_pads) in enumerate(rows):
    aget, ch = divmod(index, 64)
    print(f"{plane}\t{section}\t{strip}\t0\t0\t{aget}\t{ch}\t{off_pad}\t{off_strip}\t{len_pads}")
